// WorkspaceInfo reports runtime metadata, asset availability, and baseline resource usage.
type WorkspaceInfo struct {
	AppName         string  `json:"appName"`
	AppVersion      string  `json:"appVersion"`
	GoVersion       string  `json:"goVersion"`
	OS              string  `json:"os"`
	Arch            string  `json:"arch"`
	CreativeBaseDir string  `json:"creativeBaseDir"`
	CreativeBaseOK  bool    `json:"creativeBaseOk"`
	DBPath          string  `json:"dbPath"`
	ExportsDir      string  `json:"exportsDir"`
	HeapAllocMB     float64 `json:"heapAllocMb"`
	ProcessRSSMB    float64 `json:"processRssMb"`
	NumGoroutine    int     `json:"numGoroutine"`
}

// ExportRequest carries base64-encoded raster output generated by the canvas renderer.
type ExportRequest struct {
	DocumentID string `json:"documentId"`
	Format     string `json:"format"` // png | jpeg
	DataBase64 string `json:"dataBase64"`
	FileName   string `json:"fileName,omitempty"`
}

// Service coordinates document persistence, seed initialization, and verified raster export.
type Service struct {
	store           *sqlite.Store
	creativeBaseDir string
	creativeBaseOK  func() bool
	exportsDir      string
	appVersion      string
}

// NewService constructs the editor use-case service.
func NewService(store *sqlite.Store, creativeBaseDir string, creativeBaseOK func() bool, exportsDir string, appVersion string) *Service {
	return &Service{
		store:           store,
		creativeBaseDir: creativeBaseDir,
		creativeBaseOK:  creativeBaseOK,
		exportsDir:      exportsDir,
		appVersion:      appVersion,
	}
}

// GetWorkspaceInfo returns current workspace paths and process memory baseline.
func (s *Service) GetWorkspaceInfo() WorkspaceInfo {
	var mem runtime.MemStats
	runtime.ReadMemStats(&mem)

	baseOK := false
	if s.creativeBaseOK != nil {
		baseOK = s.creativeBaseOK()
	}

	return WorkspaceInfo{
		AppName:         "InstaGo",
		AppVersion:      s.appVersion,
		GoVersion:       runtime.Version(),
		OS:              runtime.GOOS,
		Arch:            runtime.GOARCH,
		CreativeBaseDir: s.creativeBaseDir,
		CreativeBaseOK:  baseOK,
		DBPath:          s.store.Path(),
		ExportsDir:      s.exportsDir,
		HeapAllocMB:     float64(mem.HeapAlloc) / (1024 * 1024),
		ProcessRSSMB:    readLinuxProcessRSSMB(),
		NumGoroutine:    runtime.NumGoroutine(),
	}
}

// EnsureSeedDocument loads the representative V5 document or creates it in SQLite on first launch.
func (s *Service) EnsureSeedDocument(ctx context.Context) (document.Document, error) {
	doc, err := s.store.GetDocument(ctx, seed.RepresentativeV5ComboID)
	if err == nil {
		return doc, nil
	}
	if !errors.Is(err, sql.ErrNoRows) {
		return document.Document{}, err
	}
	initial := seed.NewV5ComboPage2Document()
	return s.store.SaveDocument(ctx, initial, "seed: V5 02-combo-02 initial conversion")
}

// GetDocument retrieves a persisted document by ID.
func (s *Service) GetDocument(ctx context.Context, id string) (document.Document, error) {
	return s.store.GetDocument(ctx, id)
}

// ListDocuments returns all persisted documents.
func (s *Service) ListDocuments(ctx context.Context) ([]document.Document, error) {
	return s.store.ListDocuments(ctx)
}

// SaveDocument validates and saves an updated editable document as a new revision.
func (s *Service) SaveDocument(ctx context.Context, doc document.Document, note string) (document.Document, error) {
	if strings.TrimSpace(note) == "" {
		note = "manual edit"
	}
	return s.store.SaveDocument(ctx, doc, note)
}

// ResetSeedDocument restores the representative V5 baseline as a new revision in SQLite.
func (s *Service) ResetSeedDocument(ctx context.Context) (document.Document, error) {
	fresh := seed.NewV5ComboPage2Document()
	return s.store.SaveDocument(ctx, fresh, "reset to V5 02-combo-02 baseline")
}

// ListExports returns recent verified export records for a document.
func (s *Service) ListExports(ctx context.Context, documentID string) ([]sqlite.ExportRecord, error) {
	return s.store.ListExports(ctx, documentID)
}

// ExportAsset decodes the rendered raster image, verifies format and exact pixel dimensions
// against the persisted document, writes atomically to exportsDir, and records metadata in SQLite.
func (s *Service) ExportAsset(ctx context.Context, req ExportRequest) (sqlite.ExportRecord, error) {
	doc, err := s.store.GetDocument(ctx, req.DocumentID)
	if err != nil {
		return sqlite.ExportRecord{}, fmt.Errorf("load document %s: %w", req.DocumentID, err)
	}

	ext, expectedImageFmt, err := normalizeExportFormat(req.Format)
	if err != nil {
		return sqlite.ExportRecord{}, err
	}

	rawB64 := req.DataBase64
	if idx := strings.Index(rawB64, ","); idx != -1 && strings.HasPrefix(rawB64[:idx], "data:") {
		rawB64 = rawB64[idx+1:]
	}
	raw, err := base64.StdEncoding.DecodeString(strings.TrimSpace(rawB64))
	if err != nil {
		return sqlite.ExportRecord{}, fmt.Errorf("decode base64 raster: %w", err)
	}
	if len(raw) == 0 {
		return sqlite.ExportRecord{}, errors.New("empty raster payload")
	}

	cfg, actualFmt, err := image.DecodeConfig(bytes.NewReader(raw))
	if err != nil {
		return sqlite.ExportRecord{}, fmt.Errorf("invalid raster image: %w", err)
	}
	if actualFmt != expectedImageFmt {
		return sqlite.ExportRecord{}, fmt.Errorf("raster format mismatch: got %q, expected %q", actualFmt, expectedImageFmt)
	}
	if cfg.Width != doc.ExportWidth || cfg.Height != doc.ExportHeight {
		return sqlite.ExportRecord{}, fmt.Errorf(
			"export dimension mismatch: got %dx%d, expected %dx%d for format %s",
			cfg.Width, cfg.Height, doc.ExportWidth, doc.ExportHeight, doc.Format,
		)
	}

	if err := os.MkdirAll(s.exportsDir, 0o750); err != nil {
		return sqlite.ExportRecord{}, fmt.Errorf("create exports directory: %w", err)
	}

	baseName := sanitizeFileStem(req.FileName)
	if baseName == "" {
		baseName = fmt.Sprintf("%s-rev%03d-%s", sanitizeFileStem(doc.ID), doc.Revision, time.Now().UTC().Format("20060102-150405"))
	}
	targetPath := filepath.Join(s.exportsDir, baseName+"."+ext)

	if err := writeFileAtomic(targetPath, raw); err != nil {
		return sqlite.ExportRecord{}, err
	}

	sum := sha256.Sum256(raw)
	rec := sqlite.ExportRecord{
		ID:         uuid.NewString(),
		DocumentID: doc.ID,
		Revision:   doc.Revision,
		Format:     ext,
		FilePath:   targetPath,
		SHA256:     hex.EncodeToString(sum[:]),
		Width:      cfg.Width,
		Height:     cfg.Height,
		Bytes:      int64(len(raw)),
		CreatedAt:  time.Now().UTC().Format(time.RFC3339),
	}
	if err := s.store.RecordExport(ctx, rec); err != nil {
		return sqlite.ExportRecord{}, err
	}
	return rec, nil
}

func normalizeExportFormat(format string) (ext string, imageFmt string, err error) {
	switch strings.ToLower(strings.TrimSpace(format)) {
	case "png":
		return "png", "png", nil
	case "jpg", "jpeg":
		return "jpg", "jpeg", nil
	default:
		return "", "", fmt.Errorf("unsupported export format %q (use png or jpg)", format)
	}
}

func sanitizeFileStem(name string) string {
	name = strings.TrimSpace(filepath.Base(name))
	name = strings.TrimSuffix(name, filepath.Ext(name))
	var b strings.Builder
	for _, r := range name {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '-', r == '_':
			b.WriteRune(r)
		case r == ' ':
			b.WriteRune('-')
		}
	}
	return strings.Trim(b.String(), "-_")
}

func writeFileAtomic(targetPath string, data []byte) error {
	dir := filepath.Dir(targetPath)
	tmp, err := os.CreateTemp(dir, ".instago-export-*")
	if err != nil {
		return fmt.Errorf("create temp export: %w", err)
	}
	tmpPath := tmp.Name()
	cleanup := true
	defer func() {
		if cleanup {
			_ = os.Remove(tmpPath)
		}
	}()

	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("write temp export: %w", err)
	}
	if err := tmp.Chmod(0o640); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("chmod temp export: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("close temp export: %w", err)
	}
	if err := os.Rename(tmpPath, targetPath); err != nil {
		return fmt.Errorf("rename export into place: %w", err)
	}
	cleanup = false
	return nil
}

func readLinuxProcessRSSMB() float64 {
	if runtime.GOOS != "linux" {
		return 0
	}
	raw, err := os.ReadFile("/proc/self/statm")
	if err != nil {
		return 0
	}
	fields := strings.Fields(string(raw))
	if len(fields) < 2 {
		return 0
	}
	rssPages, err := strconv.ParseInt(fields[1], 10, 64)
	if err != nil {
		return 0
	}
	rssBytes := rssPages * int64(os.Getpagesize())
	return float64(rssBytes) / (1024 * 1024)
}
